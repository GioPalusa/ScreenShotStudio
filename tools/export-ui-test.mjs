// Real host/renderer coverage for automatic checks and explicit export overrides.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';
import assert from 'node:assert/strict';
import { execBrowserTest as execFile } from './browser-test-runner.mjs';
import { fileURLToPath } from 'node:url';
import { createStudioService } from '../host/service.mjs';
import { createNewProject } from '../host/new-project.mjs';
import { encodePNG } from './png.mjs';
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'studio-export-ui-'));
const appPath = path.join(temp, 'app'), projectPath = path.join(temp, 'Test.sss'), output = path.join(temp, 'export');
const chrome = ['/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', process.env.CHROME_PATH].filter(Boolean).find(f => fs.existsSync(f));
assert.ok(chrome, 'Chrome is required.');
let service, server;
const writes = [];
try {
  fs.cpSync(path.join(root, 'app'), appPath, { recursive: true });
  createNewProject(projectPath, {});
  const project = JSON.parse(fs.readFileSync(path.join(projectPath, 'studio.json')));
  // Use a real layout warning: original-language text no longer needs translation review.
  project.slides[0].layouts.iphone.layers.push({ id: 'outside', type: 'shape', cx: 0, cy: 100, w: 100, h: 100 });
  project.slides.push({ id: 'clean', name: 'Clean image', theme: 'starter', layouts: { iphone: { template: 'custom', panorama: false, layers: [{ id: 'art', type: 'art', src: 'image.png', cx: 660, cy: 900, w: 500, h: 500 }] } } });
  fs.writeFileSync(path.join(projectPath, 'studio.json'), JSON.stringify(project));
  fs.mkdirSync(path.join(projectPath, 'assets/art'), { recursive: true });
  fs.writeFileSync(path.join(projectPath, 'assets/art/image.png'), encodePNG({ width: 600, height: 600, data: Buffer.alloc(600 * 600 * 4, 255), channels: 3 }));
  fs.writeFileSync(path.join(appPath, 'export-test.html'), '<html><head><link rel="stylesheet" href="/app/css/studio.css"></head><body><div id="root"></div><pre id="result">PENDING</pre><script type="module" src="/app/export-test.js"></script></body></html>');
  fs.writeFileSync(path.join(appPath, 'export-test.js'), `
    const result=document.querySelector('#result'),check=(v,m)=>{if(!v)throw new Error(m)};
    const waitFor=async fn=>{for(let i=0;i<1500;i++){if(fn())return;await new Promise(r=>setTimeout(r,10));}throw new Error('Timeout: '+document.body.textContent)};
    const button=text=>[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===text);
    const counts=()=>document.querySelector('.export-check-counts')?.textContent;
    const files=async()=>await (await fetch('/api/exports')).json();
    try {
      const {engine,loadAll}=await import('/app/js/store.js');await loadAll();
      const {openExport,runExport}=await import('/app/js/ui/export.js');
      const ctx={go(){}};
      let m=openExport(ctx);
      check(button('Checking…')?.disabled,'Export must be disabled until automatic checks finish');
      await waitFor(()=>button('Export anyway')&&!button('Export anyway').disabled);
      check(counts()==='1 blocking error1 warning','Errors and warnings must be counted separately: '+counts());
      check((await files()).files.length===0,'Automatic checks must not publish images');
      check(document.querySelector('.result-list').textContent.includes('Screenshot'),'Missing capture must be explained');
      check(!document.querySelector('.result-list').textContent.includes('language review'),'Original text must not need translation review');
      const slides=[...document.querySelectorAll('.export-columns .field')][2].querySelectorAll('input');
      slides[1].click();await waitFor(()=>button('Export anyway')&&!button('Export anyway').disabled);
      check(counts()==='1 blocking error1 warning','Selected missing slide retains its own counts');
      button('Export anyway').click();await waitFor(()=>button('Show in Finder'));
      check(document.body.textContent.includes('1 image written'),'Explicit override must write the missing-image placeholder');
      m.close();
      m=openExport(ctx);await waitFor(()=>button('Export anyway')&&!button('Export anyway').disabled);
      const fields=[...document.querySelectorAll('.export-columns .field')];
      fields[2].querySelectorAll('input')[0].click();
      await waitFor(()=>button('Export images')&&!button('Export images').disabled);
      check(counts()==='0 blocking errors0 warnings','Deselecting the problem slide must clear both counts');
      fields[0].querySelectorAll('button')[1].click();check(button('Export images').disabled,'Empty selection must disable export');
      fields[0].querySelectorAll('button')[0].click();
      await waitFor(()=>button('Export images')&&!button('Export images').disabled);
      check(counts()==='0 blocking errors0 warnings','Rapid selection changes must not restore a stale report');
      button('Export images').click();await waitFor(()=>button('Show in Finder'));m.close();
      const selected={locales:['en-US'],devices:['iphone'],slides:engine.project.slides};
      const strict=await runExport({...selected,mode:'final'});
      check(strict.blocked&&strict.written===0,'Strict export must still reject unresolved issues');
      const changed=await runExport({...selected,mode:'draft',allowPlaceholders:true,onPreflight:()=>false});
      check(changed.checked&&changed.blocked&&changed.written===0,'A changed/unapproved report must stop before writing');
      m=openExport(ctx);m.close();await new Promise(r=>setTimeout(r,500));
      check((await files()).files.length===2,'Checks, cancellation and rejected exports must publish no extra runs');
      result.textContent='PASS: automatic preflight before writing; separate error/warning counts; selected scope; empty and rapid selections; explicit override includes placeholders; clean final; strict rejection; changed-report guard; close cancellation';
    }catch(e){result.textContent='FAIL: '+e.stack;}
  `);
  service = createStudioService({ appPath, projectPath, exportPath: output });
  server = http.createServer((req, res) => { if (req.method === 'POST' && req.url.startsWith('/api/export?')) writes.push(req.url); service.handle(req, res, server.address().port); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const stdout = await new Promise((resolve, reject) => execFile(chrome, ['--headless', '--disable-gpu', '--no-first-run', '--no-sandbox', `--user-data-dir=${path.join(temp, 'chrome')}`, '--window-size=1200,950', `http://127.0.0.1:${server.address().port}/app/export-test.html`], { timeout: 60000, maxBuffer: 3e6 }, (error, out, stderr) => { fs.writeFileSync('/tmp/studio-export-ui-dom.html', out); fs.writeFileSync('/tmp/studio-export-ui-chrome.log', stderr); error ? reject(error) : resolve(out); }));
  const verdict = stdout.match(/<pre id="result">([\s\S]*?)<\/pre>/)?.[1] ?? 'No result';
  assert.match(verdict, /^PASS:/, verdict);
  const runs = fs.readdirSync(output).filter(f => !f.startsWith('.'));
  assert.equal(runs.length, 2); assert.equal(writes.length, 2);
  const manifests = runs.map(run => JSON.parse(fs.readFileSync(path.join(output, run, 'manifest.json'))));
  const draft = manifests.find(m => m.mode === 'draft'), final = manifests.find(m => m.mode === 'final');
  assert.equal(draft.files.length, 1); assert.equal(draft.files[0].slideId, 'first-slide');
  assert.deepEqual(draft.report.issues.map(i => i.level).sort(), ['error', 'warn']);
  assert.equal(draft.report.skipped.length, 0);
  assert.equal(final.files.length, 1); assert.equal(final.files[0].slideId, 'clean'); assert.deepEqual(final.report.issues, []);
  for (const manifest of manifests) for (const file of manifest.files) assert.equal(fs.readFileSync(path.join(output, runs.find(r => r.startsWith(manifest.mode+'-')), file.path))[25], 2, 'PNG must be RGB without alpha');
  console.log(verdict);
} finally {
  server?.closeAllConnections(); await new Promise(resolve => server ? server.close(resolve) : resolve()); service?.close();
  fs.rmSync(temp, { recursive: true, force: true });
}
